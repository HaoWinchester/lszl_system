'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context={window:{}};vm.createContext(context);
for(const file of ['115-practice-mode-policy','111-practice-session-core','112-practice-answer-sheet'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../src',file+'.js'),'utf8'),context);
const {KGPracticeModePolicy:policy,KGPracticeSessionCore:core,KGPracticeAnswerSheet:sheet}=context.window;
assert.equal(policy.forMode('practice',{instantFeedback:false}).canExplain,false);
assert.equal(policy.forMode('practice',{instantFeedback:false}).showCorrectness,false);
assert.equal(policy.forMode('practice').showCorrectness,true);
for(const mode of ['challenge','scholar','revenge'])assert.equal(policy.forMode(mode,{instantFeedback:false}).showCorrectness,true);
assert.equal(policy.forMode('practice',{instantFeedback:false,reviewOnly:true}).showCorrectness,true);
assert.equal(core.normalizeSession({}).runtimeState.instantFeedback,true);
assert.equal(core.resumableRuntime({runtimeState:{instantFeedback:false}}).instantFeedback,false);
const root={innerHTML:'',addEventListener(){}};const view=sheet.mount(root);
const session={mode:'practice',runtimeState:{instantFeedback:false},questions:[{questionId:'q1'},{questionId:'q2'},{questionId:'q3'}],answers:{q1:{correct:true},q2:{correct:false}}};
view.render(session,'q1','wrong');
assert(!/正确|错误|错题|is-correct|is-wrong/.test(root.innerHTML));
assert(root.innerHTML.includes('已答'));assert(root.innerHTML.includes('data-question-id="q2"'));
view.render({...session,runtimeState:{instantFeedback:true}},'q1');
assert(root.innerHTML.includes('is-correct'));assert(root.innerHTML.includes('is-wrong'));
console.log('practice instant feedback contracts passed');
