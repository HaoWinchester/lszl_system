'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({ window: {}, document: { readyState: 'loading', addEventListener() {} } });
for (const file of ['111-practice-session-core.js', '103-support-center.js']) vm.runInContext(fs.readFileSync(path.join(root, 'src', file), 'utf8'), context);
const core = context.window.KGPracticeSessionCore;
const session = { questions: ['a','b','c','d'].map(questionId => ({ questionId })), answers: { a: {correct:true}, c: {timedOut:true} } };
assert.equal(typeof core.nextUnansweredIndex, 'function', 'shared session core exposes next unanswered navigation');
assert.equal(core.nextUnansweredIndex(session, 0), 1);
assert.equal(core.nextUnansweredIndex(session, 1), 3, 'skip graded and timed-out answers');
assert.equal(core.nextUnansweredIndex(session, 3), 1, 'wrap in frozen question order');
assert.equal(core.nextUnansweredIndex({ ...session, answers: {a:{},b:{},c:{},d:{}} }, 0), -1);
assert.equal(core.nextUnansweredIndex({ questions: [], answers: {} }, 0), -1);
const feedback = context.window.KGSupportCenter.questionFeedbackDraft({questionId:'q1',paperId:'p1',releaseId:'r2',sessionId:'s3'});
assert.equal(feedback.type, 'content');
for (const value of ['q1','p1','r2','s3']) assert.ok(feedback.detail.includes(value), 'feedback retains '+value);
assert.ok(!feedback.detail.includes('undefined'));
console.log('practice-experience-ok');

vm.runInContext(fs.readFileSync(path.join(root, 'src/113-practice-result-report.js'), 'utf8'), context);
let onFeedback;
const button = { dataset: { questionFeedback: 'q1' }, addEventListener(type, callback) { onFeedback = callback; } };
const content = { innerHTML: '' };
const section = { innerHTML: '', querySelector: () => content, querySelectorAll(selector) { return selector === '[data-question-feedback]' ? [button] : []; } };
const reportRoot = { innerHTML:'', classList:{add(){}}, querySelector(selector) { return selector === '[data-question-review]' ? section : null; }, querySelectorAll() { return []; } };
context.window.KGPracticeResultReport.render(reportRoot, { official:false, wrongQuestionIds:['q1'], releaseId:'r2',paperId:'p1',sessionId:'s3' }, {questions:[{id:'q1',stem:'Example',explanation:'   '}],answers:{q1:{correct:false}}});
assert.match(content.innerHTML, /data-question-feedback="q1"/, 'missing explanation offers contextual feedback');
assert.match(content.innerHTML, /暂无解析/);
let opened;
context.window.KGSupportCenter = {openQuestionFeedback: value => {opened = value;}};
onFeedback();
assert.equal(opened.questionId, 'q1');
assert.equal(opened.releaseId, 'r2');
assert.equal(opened.paperId, 'p1');

// Open the real support form: context is visible for review and generic entry stays clean.
const nodes = Object.fromEntries(['engagementDialogBackdrop','engagementDialogTitle','engagementDialogSubtitle','engagementDialogBody','engagementDialogClose','feedbackTabContent','feedbackForm','feedbackType','feedbackTitle','feedbackDetail'].map(id => [id, {id, value:'',hidden:true,innerHTML:'',addEventListener(){},querySelectorAll(){return []},focus(){}}]));
nodes.engagementDialogBody.querySelector = selector => selector === '#feedbackTabContent' ? nodes.feedbackTabContent : null;
const openingContext = vm.createContext({window:{KGEngagementRepository:{unreadSummary:async()=>({})}},requestAnimationFrame:callback=>callback(),document:{readyState:'loading',addEventListener(){},getElementById:id=>nodes[id],body:{classList:{add(){}}}}});
vm.runInContext(fs.readFileSync(path.join(root,'src/103-support-center.js'),'utf8'),openingContext);
openingContext.window.KGSupportCenter.openQuestionFeedback({questionId:'q1',paperId:'p1',releaseId:'r2',sessionId:'s3'});
assert.equal(nodes.feedbackType.value,'content');
assert.match(nodes.feedbackDetail.value,/发布版本 ID：r2/);
openingContext.window.KGSupportCenter.openFeedback();
assert.equal(nodes.feedbackType.value,'suggestion');
assert.equal(nodes.feedbackDetail.value,'');
console.log('practice-feedback-form-ok');
